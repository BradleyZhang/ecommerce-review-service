package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
)

func main() {
	srcFile := "reason.go"
	outFile := "errors_gen.go"

	if len(os.Args) > 1 {
		srcFile = os.Args[1]
	}
	if len(os.Args) > 2 {
		outFile = os.Args[2]
	}

	if err := run(srcFile, outFile); err != nil {
		fmt.Fprintf(os.Stderr, "gen_func: %v\n", err)
		os.Exit(1)
	}
}

func run(srcFile, outFile string) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, srcFile, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("parse %s: %w", srcFile, err)
	}

	// 收集所有 `Name = ReasonCode{...}` 形式的变量声明
	type entry struct {
		Name string
	}
	var entries []entry

	ast.Inspect(file, func(n ast.Node) bool {
		gen, ok := n.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			return true
		}
		for _, spec := range gen.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			// 判断右侧是否为 ReasonCode 复合字面量
			if !isReasonCodeLit(vs) {
				continue
			}
			for _, name := range vs.Names {
				entries = append(entries, entry{Name: name.Name})
			}
		}
		return true
	})

	if len(entries) == 0 {
		return fmt.Errorf("no ReasonCode declarations found in %s", srcFile)
	}

	// 生成代码
	var buf bytes.Buffer
	buf.WriteString("// Code generated by tool/gen_func.go; DO NOT EDIT.\n\n")
	buf.WriteString("package gerr\n\n")

	for _, e := range entries {
		fnName := e.Name + "Err"
		fmt.Fprintf(&buf, "func %s(msg string) error {\n", fnName)
		fmt.Fprintf(&buf, "\treturn NewGRPCError(%s.Code, msg, %s.Reason)\n", e.Name, e.Name)
		buf.WriteString("}\n\n")
	}

	// gofmt
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format output: %w\n%s", err, buf.String())
	}

	// 确保输出目录存在
	if dir := filepath.Dir(outFile); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}

	return os.WriteFile(outFile, formatted, 0o644)
}

// isReasonCodeLit 判断 ValueSpec 的 Value 是否为 ReasonCode{...}
func isReasonCodeLit(vs *ast.ValueSpec) bool {
	if len(vs.Values) == 0 {
		return false
	}
	// 支持 var ( A = ReasonCode{...} ) 以及 var A, B = ReasonCode{...} 这类
	// 一般一个 ReasonCode 对应一个变量，这里只看第一个
	cl, ok := vs.Values[0].(*ast.CompositeLit)
	if !ok {
		return false
	}
	ident, ok := cl.Type.(*ast.Ident)
	if !ok {
		return false
	}
	return ident.Name == "ReasonCode"
}
